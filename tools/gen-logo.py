#!/usr/bin/env python3
"""Bake assets/mark.svg into src/ui/logo_data.rs as RGBA pixel tables for the TUI.

The TUI draws the mark with half-block characters (one text cell = 1 column x 2 rows of pixels),
so a 24 px render becomes 24 columns x 12 rows. Requires rsvg-convert and ImageMagick (`magick`).

    python3 tools/gen-logo.py
"""
import subprocess, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "mark.svg"
OUT = ROOT / "src" / "ui" / "logo_data.rs"
SIZES = {"LOGO24": 24, "LOGO16": 16}

def render(size):
    png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), str(SRC)], check=True, capture_output=True).stdout
    raw = subprocess.run(["magick", "png:-", "-depth", "8", "rgba:-"], input=png, check=True, capture_output=True).stdout
    assert len(raw) == size * size * 4, (len(raw), size)
    return [tuple(raw[i:i + 4]) for i in range(0, len(raw), 4)]

parts = ["// Generated by tools/gen-logo.py from assets/mark.svg. Do not edit by hand.\n",
         "//\n// Each table is a square of straight-alpha RGBA pixels, row-major, top row first.\n\n",
         "pub struct Logo {\n    pub size: usize,\n    pub px: &'static [u32],\n}\n\n"]
for name, size in SIZES.items():
    px = render(size)
    words = [f"0x{r:02x}{g:02x}{b:02x}{a:02x}" for (r, g, b, a) in px]
    rows = [", ".join(words[i:i + size]) for i in range(0, len(words), size)]
    parts.append(f"pub static {name}: Logo = Logo {{\n    size: {size},\n    px: &[\n")
    parts.extend(f"        {row},\n" for row in rows)
    parts.append("    ],\n};\n\n")
    # Sanity preview on stderr so a wrong orientation is obvious.
    sys.stderr.write(f"{name} ({size}px) alpha mask:\n")
    for y in range(size):
        sys.stderr.write("".join("#" if px[y * size + x][3] >= 128 else "." for x in range(size)) + "\n")
OUT.write_text("".join(parts))
print(f"wrote {OUT.relative_to(ROOT)}")
